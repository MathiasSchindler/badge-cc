#define PSM_WORD(op, a, b, d) \
    (((uint64_t)(op) << 39u) | ((uint64_t)(a) << 26u) | ((uint64_t)(b) << 13u) | (d))
#define PSM_BYTES(word) \
    (uint8_t)(word), (uint8_t)((word) >> 8u), (uint8_t)((word) >> 16u), \
    (uint8_t)((word) >> 24u), (uint8_t)((word) >> 32u), (uint8_t)((word) >> 40u), \
    (uint8_t)((word) >> 48u), (uint8_t)((word) >> 56u)

