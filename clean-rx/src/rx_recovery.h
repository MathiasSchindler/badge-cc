_Static_assert(CLEAN_RX_HT_ORDERED_FLUSH >= 0 && CLEAN_RX_HT_ORDERED_FLUSH <= 2,
    "Ordered flush diagnostic selects off, every rearm or fault-only recovery");
_Static_assert(!CLEAN_RX_HT_ORDERED_FLUSH ||
    (CLEAN_RX_HT_REARM_RECOVER && !CLEAN_RX_HT_REARM_RESET),
    "Ordered flush requires passive rearm recovery without host PHY reset");
_Static_assert(CLEAN_RX_HT_PREFIX_RECOVERY == 0 || CLEAN_RX_HT_PREFIX_RECOVERY == 1,
    "Prefix recovery diagnostic must be zero or one");
_Static_assert(!CLEAN_RX_HT_PREFIX_RECOVERY || CLEAN_RX_HT_ORDERED_FLUSH != 0,
    "Prefix recovery requires the bounded ordered flush diagnostic");

