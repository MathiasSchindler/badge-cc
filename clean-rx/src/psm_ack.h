/* Latch only the current Data submission, before automatic responses can
 * clear/reuse its hardware status. Never attribute a response's TX to Data. */
#define TX_COMPLETION_PROGRAM(X, tag, next) \
    X(tag, 0xd1u, CLEAN_DCF_REQUEST, 0x1802u, next) \
    X(tag##_CLOSED, 0x503u, CLEAN_TX_COMPLETION, 0x1800u, next) \
    X(tag##_RECORDED, 0xd0u, CLEAN_TX_COMPLETION, 0x1807u, next) \
    X(tag##_RESPONSE, 0xd1u, CLEAN_RESPONSE_PENDING, 0x1800u, next) \
    X(tag##_PENDING, 0xd1u, CLEAN_DCF_TX_PENDING, 0x1800u, next) \
    X(tag##_BUSY, 0x507u, 0x1087u, 0x1800u, tag##_DONE) \
    X(tag##_NOT_BUSY, 0x300u, 0x1801u, CLEAN_TX_COMPLETION, CLEAN_TX_COMPLETION) \
    X(tag##_DONE, 0x40au, 0x1087u, 0x1800u, tag##_PHY) \
    X(tag##_MAC_DONE, 0x301u, 0x1801u, CLEAN_TX_COMPLETION, CLEAN_TX_COMPLETION) \
    X(tag##_PHY, 0x508u, 0x1148u, 0x1800u, next) \
    X(tag##_PHY_IDLE, 0x302u, 0x1801u, CLEAN_TX_COMPLETION, CLEAN_TX_COMPLETION)

/* Closing is sticky until the next Data trigger, including after response
 * cleanup releases ownership while its hardware done bit remains set. */
#define TX_COMPLETION_CLOSE_PROGRAM(X, tag, next) \
    TX_COMPLETION_PROGRAM(X, tag, tag##_OWNER) \
    X(tag##_OWNER, 0xd1u, CLEAN_DCF_REQUEST, 0x1802u, next) \
    X(tag##_SAMPLE, 0x3f0u, 0x1087u, 0x1800u, CLEAN_TX_PRE_RESPONSE) \
    X(tag##_CLOSE, 0x303u, 0x1801u, CLEAN_TX_COMPLETION, CLEAN_TX_COMPLETION)

