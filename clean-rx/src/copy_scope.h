#ifndef CLEAN_RX_COPY_SCOPE_H
#define CLEAN_RX_COPY_SCOPE_H

#define CLEAN_COPY_SCOPE_SHM 0x4b0u
#define CLEAN_COPY_SCOPE_WORDS 80u
#define CLEAN_COPY_SCOPE_RECORD_WORDS 26u
#define CLEAN_COPY_SCOPE_US 32u
#define CLEAN_COPY_SCOPE_BUDGET 1023u
#if CLEAN_RX_HT_COPY_SCOPE >= 3
#define OBSERVER_STREAM_SCOPE_WRITE_ONLY(X) \
    X(OBSERVER_STREAM_PHASE_WRITE_ONLY,0x3f0u,0x1783u,0x1800u,CLEAN_OBSERVER_SAVE_R3) \
    X(COPY_SCOPE_HOLD_EPOCH,0x3f0u,CLEAN_COPY_SCOPE_SHM+1u,0x1800u,0x1783u) \
    X(COPY_SCOPE_HOLD_STALE,0xd1u,0x1783u,CLEAN_OBSERVER_EPOCH,COPY_SCOPE_RESTORE_STREAM) \
    X(COPY_SCOPE_HOLD_PENDING,0xdau,CLEAN_COPY_SCOPE_SHM,0x1811u,COPY_SCOPE_RESTORE_STREAM) \
    X(COPY_SCOPE_HOLD_INVALID,0xdcu,CLEAN_COPY_SCOPE_SHM,0x1814u,COPY_SCOPE_RESTORE_STREAM) \
    X(COPY_SCOPE_HOLD_ADVANCE,0xd1u,CLEAN_OBSERVER_ADVANCE,0x1801u,COPY_SCOPE_RESTORE_STREAM) \
    X(COPY_SCOPE_HOLD_R3,0x3f0u,CLEAN_OBSERVER_SAVE_R3,0x1800u,0x1783u) \
    X(COPY_SCOPE_HOLD_ACTION,0x310u,CLEAN_RX_HT_COPY_SCOPE == 3 ? 0x1800u : 0x1802u,0x1004u,0x1004u) \
    X(COPY_SCOPE_HOLD_RETURN,0x77fu,0x1780u,0x1780u,312u) \
    X(COPY_SCOPE_RESTORE_STREAM,0x3f0u,CLEAN_OBSERVER_SAVE_R3,0x1800u,0x1783u) \
    X(COPY_SCOPE_NORMAL_STREAM,0x310u,0x1802u,0x1004u,0x1004u)
#else
#define OBSERVER_STREAM_SCOPE_WRITE_ONLY(X) \
    X(OBSERVER_STREAM_PHASE_WRITE_ONLY,0x310u,0x1802u,0x1004u,0x1004u)
#endif
_Static_assert(!CLEAN_RX_HT_COPY_SCOPE ||
    (CLEAN_OBSERVER_EARLY_SHM+CLEAN_OBSERVER_EARLY_HEADER+
        (CLEAN_OBSERVER_EARLY_MAX+1u)/2u <= CLEAN_COPY_SCOPE_SHM &&
     CLEAN_COPY_SCOPE_SHM+CLEAN_COPY_SCOPE_WORDS == CLEAN_OBSERVER_SECOND_SHM),
    "Copy scope must occupy only unused first-body snapshot storage");

#if CLEAN_RX_HT_COPY_SCOPE
#define COPY_SCOPE_WORD(X,tag,offset,source) \
    X(COPY_SCOPE_##tag,0x3f0u,source,0x1800u,CLEAN_COPY_SCOPE_SHM+offset)
#define COPY_SCOPE_DATA(X,n,i) \
    COPY_SCOPE_WORD(X,DATA_##n##_##i,2u+26u*n+10u+i,CLEAN_SHM_FRAME+4u+64u+i) \
    COPY_SCOPE_WORD(X,TAIL_##n##_##i,2u+26u*n+18u+i,CLEAN_SHM_FRAME+4u+80u+i)
#define COPY_SCOPE_RECORD(X,n) \
    COPY_SCOPE_WORD(X,TSF_##n,2u+26u*n,0x1119u) \
    COPY_SCOPE_WORD(X,COUNT_##n,3u+26u*n,0x100cu) \
    COPY_SCOPE_WORD(X,STATUS1_##n,4u+26u*n,0x100du) \
    COPY_SCOPE_WORD(X,STATUS2_##n,5u+26u*n,0x100eu) \
    COPY_SCOPE_WORD(X,CONTROL_##n,6u+26u*n,0x1004u) \
    COPY_SCOPE_WORD(X,BASE_##n,7u+26u*n,0x1001u) \
    COPY_SCOPE_WORD(X,END_##n,8u+26u*n,0x102au) \
    COPY_SCOPE_WORD(X,NEXT_##n,9u+26u*n,0x102bu) \
    COPY_SCOPE_WORD(X,FIFO_##n,10u+26u*n,0x1024u) \
    COPY_SCOPE_WORD(X,CONTEXT_##n,11u+26u*n,0x1078u) \
    COPY_SCOPE_DATA(X,n,0u) COPY_SCOPE_DATA(X,n,1u) \
    COPY_SCOPE_DATA(X,n,2u) COPY_SCOPE_DATA(X,n,3u) \
    COPY_SCOPE_DATA(X,n,4u) COPY_SCOPE_DATA(X,n,5u) \
    COPY_SCOPE_DATA(X,n,6u) COPY_SCOPE_DATA(X,n,7u)
#define OBSERVER_STREAM_SCOPE_RESET(X) \
    COPY_SCOPE_WORD(X,RESET,0u,0x1800u) COPY_SCOPE_WORD(X,RESET_EPOCH,1u,0x1800u)
#define OBSERVER_STREAM_SCOPE_BEFORE(X) \
    COPY_SCOPE_WORD(X,EPOCH,1u,CLEAN_OBSERVER_EPOCH) \
    COPY_SCOPE_RECORD(X,0)
#define OBSERVER_STREAM_SCOPE_CONTROL(X) \
    X(COPY_SCOPE_STREAM,0x310u,CLEAN_RX_HT_COPY_SCOPE == 1 ? 0x1802u : 0x1800u,0x1004u,0x1004u)
#define COPY_SCOPE_REASON(X,tag,value) \
    COPY_SCOPE_WORD(X,REASON_##tag,0u,0x1800u|value) \
    X(COPY_SCOPE_GO_##tag,0x77fu,0x1780u,0x1780u,COPY_SCOPE_TSF_2)
#define OBSERVER_STREAM_SCOPE_AFTER(X) \
    COPY_SCOPE_RECORD(X,1) \
    COPY_SCOPE_WORD(X,BUDGET,55u,0x1800u|CLEAN_COPY_SCOPE_BUDGET) \
    X(COPY_SCOPE_WAIT,0x50fu,0x100du,0x1800u,COPY_SCOPE_REASON_ABORT) \
    X(COPY_SCOPE_EOF,0x50eu,0x100du,0x1800u,COPY_SCOPE_REASON_EOF) \
    X(COPY_SCOPE_TIME,0x1d0u,0x1119u,CLEAN_COPY_SCOPE_SHM+28u,CLEAN_COPY_SCOPE_SHM+54u) \
    X(COPY_SCOPE_TIME_DONE,0xdbu,CLEAN_COPY_SCOPE_SHM+54u,0x1800u|CLEAN_COPY_SCOPE_US,COPY_SCOPE_REASON_TIME) \
    X(COPY_SCOPE_EXHAUSTED,0xd0u,CLEAN_COPY_SCOPE_SHM+55u,0x1800u,COPY_SCOPE_REASON_BUDGET) \
    X(COPY_SCOPE_TICK,0x1d0u,CLEAN_COPY_SCOPE_SHM+55u,0x1801u,CLEAN_COPY_SCOPE_SHM+55u) \
    X(COPY_SCOPE_AGAIN,0x77fu,0x1780u,0x1780u,COPY_SCOPE_WAIT) \
    COPY_SCOPE_REASON(X,TIME,1u) COPY_SCOPE_REASON(X,EOF,2u) \
    COPY_SCOPE_REASON(X,ABORT,3u) COPY_SCOPE_REASON(X,BUDGET,4u) \
    COPY_SCOPE_RECORD(X,2) \
    X(COPY_SCOPE_COMMIT,0x1c0u,CLEAN_COPY_SCOPE_SHM,0x1810u,CLEAN_COPY_SCOPE_SHM)
#else
#define OBSERVER_STREAM_SCOPE_RESET(X)
#define OBSERVER_STREAM_SCOPE_BEFORE(X)
#define OBSERVER_STREAM_SCOPE_CONTROL(X)
#define OBSERVER_STREAM_SCOPE_AFTER(X)
#endif
#endif
