#ifndef UNIVERSE26_NAMETAG_MEASURE_H
#define UNIVERSE26_NAMETAG_MEASURE_H

#include "usb_report.h"

#define NAMETAG_M2_TEST 0x4e4d0002u
#define NAMETAG_M2_MAGIC 0x324d544eu
#define NAMETAG_M2_WORDS 512u
#define NAMETAG_M2_CHUNK 24u
#define NAMETAG_M2_PAGES ((NAMETAG_M2_WORDS * 4u + 23u) / 24u)
#define NAMETAG_M2_SAMPLES 32u
#define NAMETAG_M2_BENCHES 8u
#define NAMETAG_M2_LOOPS 10u
#define NAMETAG_M2_CACHED_TEXT 1u
#define NAMETAG_M2_DIRTY_TRANSFER 2u
#define NAMETAG_M2_PRESENT_PROFILE 4u

enum {
    M2_MAGIC, M2_VERSION, M2_ERROR, M2_STAGE, M2_FLAGS, M2_LOOP_COUNT,
    M2_DURATION, M2_FRAMES, M2_BEFORE = 8, M2_AFTER = 20,
    M2_OLD_TICKS = 32, M2_OLD_SOF, M2_NEW_TICKS, M2_NEW_SOF,
    M2_SYS_KHZ_Q5, M2_REF_KHZ_Q5, M2_TE_OFF_EDGES, M2_TE_ON_EDGES,
    M2_TE_PERIOD_COUNT, M2_TE_WIDTH_COUNT, M2_TE_TIMEOUTS, M2_SOF_MAX_STEP,
    M2_SKIPPED_FRAMES, M2_LOOP_TICKS, M2_LOOP_SOF, M2_FINAL_TICKS, M2_FINAL_SOF,
    M2_TE_INITIAL, M2_TE_HIGH_SAMPLES, M2_TE_LOW_SAMPLES, M2_DETAIL,
    M2_CACHE_PREPARE_TICKS, M2_CACHE_BYTES,
    M2_DIFF_BENCH_PIXELS, M2_DIFF_BENCH_REGIONS, M2_DIFF_BENCH_FULL,
    M2_DIFF_ANIMATION_PIXELS, M2_DIFF_ANIMATION_REGIONS, M2_DIFF_ANIMATION_FULL,
    M2_DIFF_ANIMATION_FRAMES, M2_DIFF_STATE_BYTES, M2_DIFF_GRID,
    M2_BENCH_BASE = 64, M2_TE_PERIOD_BASE = 320, M2_TE_WIDTH_BASE = 352,
    M2_LOOP_BASE = 384, M2_TE_TRANSFER_BASE = 404, M2_FINAL_CLOCK = 436,
    M2_DIFF_PRESENT_BASE = 460,
    M2_DIFF_WRITER_TICKS = 492, M2_DIFF_SERVICE_TICKS, M2_DIFF_SERVICE_CALLS
};
enum {
    M2_FULL_TRANSFER, M2_FOOTER_TRANSFER, M2_TILE_TRANSFER, M2_COMMANDS,
    M2_BACKGROUND, M2_TEXT, M2_RENDER, M2_RENDER_TRANSFER
};
enum {
    M2_CALIBRATE = 1, M2_CLOCK, M2_DISPLAY, M2_TE, M2_BENCHMARK,
    M2_ANIMATION, M2_CONTRAST, M2_DONE
};
enum {
    M2_OK, M2_USB_ERROR, M2_CANCELLED, M2_TIMEOUT, M2_NO_SOF,
    M2_CLOCK_ERROR, M2_TIMER_ERROR, M2_FONT_ERROR, M2_DISPLAY_ERROR
};

int nametag_m2_page(uint8_t out[64], const uint32_t words[NAMETAG_M2_WORDS],
    uint32_t build, const uint8_t nonce[16], uint32_t page);
usb_record_result_t nametag_m2_page_decode(uint32_t words[NAMETAG_M2_WORDS],
    const uint8_t *wire, uint32_t length, uint32_t build, const uint8_t nonce[16],
    uint32_t page);
/* Nearest-rank percentiles; input remains unchanged. */
int nametag_m2_statistics(const uint32_t *samples, uint32_t count, uint32_t out[4]);

#endif
